#!/usr/bin/env python3
"""Convert a gem5 CommMonitor protobuf memory trace into the DAMOV2 text trace
format consumed by `damov-locality`.

gem5's stock CommMonitor emits a gzipped protobuf packet trace
(`packet.proto`). When your gem5 build only offers that format (i.e.
damov_se.py fell back to the protobuf probe), run this converter to produce the
plain `R/W addr size` text that TraceReader understands.

Usage:
  scripts/proto2trace.py --in out/stream/Add/trace/trace.proto.gz \
                         --out out/stream/Add/trace/trace.gz

Requires gem5's generated `packet_pb2.py` on PYTHONPATH (built alongside gem5 in
`build/<ISA>/proto/`), or the `protobuf` package plus gem5's `packet.proto`.
"""
import argparse
import gzip
import struct
import sys


def read_delimited(stream, message):
    """Read one length-delimited protobuf message (gem5's format)."""
    size_buf = b""
    while True:
        b = stream.read(1)
        if not b:
            return False
        size_buf += b
        if (b[0] & 0x80) == 0:
            break
    # Decode varint length.
    length, shift, val = 0, 0, 0
    for byte in size_buf:
        val |= (byte & 0x7F) << shift
        shift += 7
    length = val
    data = stream.read(length)
    if len(data) < length:
        return False
    message.ParseFromString(data)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    try:
        import packet_pb2  # type: ignore  (generated by gem5's protoc step)
    except ImportError:
        sys.exit("error: packet_pb2 not found. Add gem5's build/<ISA>/proto to "
                 "PYTHONPATH, or generate it: "
                 "protoc --python_out=. src/proto/packet.proto")

    opener = gzip.open if args.inp.endswith(".gz") else open
    out_opener = gzip.open if args.out.endswith(".gz") else open

    header = packet_pb2.PacketHeader()
    with opener(args.inp, "rb") as fin:
        # gem5 traces begin with a magic string "gem5" then a header message.
        magic = fin.read(4)
        if magic != b"gem5":
            fin.seek(0)
        read_delimited(fin, header)
        n = 0
        with out_opener(args.out, "wt") as fout:
            pkt = packet_pb2.Packet()
            while read_delimited(fin, pkt):
                rw = "W" if getattr(pkt, "cmd", 1) in (1, 4) else "R"
                size = getattr(pkt, "size", 0)
                fout.write(f"{rw} 0x{pkt.addr:x} {size}\n")
                n += 1
                pkt.Clear()
    print(f"converted {n} packets -> {args.out}")


if __name__ == "__main__":
    main()
